let x = 10;

console.log(+x);   // Unary plus: converts to number       --> 10
console.log(-x);   // Unary minus: changes sign            --> -10
console.log(++x);  // Increment: increases value by 1      --> 11
console.log(--x);  // Decrement: decreases value by 1      --> 10
console.log(!true); // Logical NOT: changes true to false  --> false
